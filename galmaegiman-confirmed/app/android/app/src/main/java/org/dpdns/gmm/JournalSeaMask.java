  private static final float[][] NIGHT_FIXED_HOLES = nightHoles();

  private JournalSeaMask() {}

  private static float[][] nightHoles() {
    float[][] result = new float[FIXED_HOLES.length + NIGHT_EXTRA_HOLES.length][];
    System.arraycopy(FIXED_HOLES, 0, result, 0, FIXED_HOLES.length);
    System.arraycopy(NIGHT_EXTRA_HOLES, 0, result, FIXED_HOLES.length, NIGHT_EXTRA_HOLES.length);
    return result;
  }

  private static Region raster(float[][] polygons, Matrix scale, Region bounds) {
    Region combined = new Region(), piece = new Region();
    Path path = new Path();
    for (float[] polygon : polygons) {
      path.rewind();
      path.moveTo(polygon[0], polygon[1]);
      for (int i = 2; i < polygon.length; i += 2) path.lineTo(polygon[i], polygon[i + 1]);
      path.close();
      path.transform(scale);
      piece.setPath(path, bounds);
      combined.op(piece, Region.Op.UNION);
    }
    return combined;
  }

  static Region region(int width, int height) {
    return region(width, height, LocalTimeTheme.Phase.DAY);
  }

  static Region region(int width, int height, LocalTimeTheme.Phase phase) {
    Matrix scale = new Matrix();
    scale.setScale(
        width / (float) JournalAmbient.SOURCE_WIDTH, height / (float) JournalAmbient.SOURCE_HEIGHT);
    Region bounds = new Region(0, 0, width, height);
    Region region = raster(water(phase), scale, bounds),
        fixed = raster(holes(phase), scale, bounds);
    region.op(fixed, Region.Op.DIFFERENCE);
    return region;
  }

  static boolean contains(float x, float y) {
    return contains(x, y, LocalTimeTheme.Phase.DAY);
  }

  static boolean contains(float x, float y, LocalTimeTheme.Phase phase) {
    return in(water(phase), x, y) && !in(holes(phase), x, y);
  }

  static float[][] water(LocalTimeTheme.Phase phase) {
    return WATER_POLYGONS;
  }

  static float[][] holes(LocalTimeTheme.Phase phase) {
    return phase == LocalTimeTheme.Phase.NIGHT ? NIGHT_FIXED_HOLES : FIXED_HOLES;
  }

  private static boolean in(float[][] polygons, float x, float y) {
    for (float[] polygon : polygons) {
      boolean inside = false;
      for (int i = 0, j = polygon.length - 2; i < polygon.length; j = i, i += 2) {
        float xi = polygon[i], yi = polygon[i + 1], xj = polygon[j], yj = polygon[j + 1];
        if ((yi > y) != (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) inside = !inside;
      }
      if (inside) return true;
    }
    return false;
  }
